const { test, expect } = require("@playwright/test");
const AxeBuilder = require("@axe-core/playwright").default;

test("real patient registration, profile contacts/guardian/address, duplicate review, merge and old-MRN search", async ({ page }) => {
  const clientErrors = [];
  page.on("pageerror", (error) => clientErrors.push(error.message));
  await page.route("**/api/v1/**", async (route) => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname.replace(/^.*\/api\/v1/, "");
    if (request.method() === "OPTIONS") return route.fulfill({ status: 204, headers: { "access-control-allow-origin": "http://127.0.0.1:3109", "access-control-allow-credentials": "true", "access-control-allow-headers": "authorization,content-type", "access-control-allow-methods": "GET,POST,PATCH,DELETE,OPTIONS" } });
    const response = await route.fetch({ url: process.env.E2E_API_BASEURL + path + url.search, timeout: 90000 });
    await route.fulfill({ response, headers: { ...response.headers(), "access-control-allow-origin": "http://127.0.0.1:3109", "access-control-allow-credentials": "true" } });
  });
  await page.goto("/login");
  await page.getByLabel("User ID or email", { exact: true }).fill(process.env.E2E_LOGIN_ID);
  await page.getByLabel("Password", { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/dashboard/);
  console.info("Patients: real login passed");
  await page.getByRole("link", { name: "Patients", exact: true }).click();
  await page.getByRole("link", { name: "Register patient", exact: true }).click();
  const fillPatient = async () => {
    await page.getByLabel("First name", { exact: false }).fill("Browser");
    await page.getByLabel("Last name", { exact: true }).fill("Patient");
    await page.getByLabel("Date of birth", { exact: true }).fill("2000-05-06");
    await page.getByLabel("Phone", { exact: true }).fill("01388887777");
    await page.getByLabel("Sex", { exact: true }).selectOption("female");
  };
  await fillPatient();
  console.info("Patients: registration form filled");
  await page.getByRole("button", { name: "Check for duplicates" }).click();
  await expect(page.getByText(/No matching patients found/)).toBeVisible();
  await page.getByRole("button", { name: "Register patient", exact: true }).click();
  await expect(page).toHaveURL(/patients\/[0-9a-f-]+$/);
  const targetId = page.url().split("/").at(-1);
  console.info("Patients: target registered");
  await expect(page.getByRole("heading", { name: "Browser Patient", exact: true })).toBeVisible();
  expect(await page.locator("p.font-mono").innerText()).toMatch(/^\d{6}$/);
  await page.getByRole("button", { name: "Edit demographics" }).click();
  await page.getByLabel("Preferred name", { exact: true }).fill("Browser Preferred");
  await page.getByRole("button", { name: "Save patient record" }).click();
  await expect(page.getByRole("dialog")).toBeHidden();
  await page.getByRole("button", { name: "Contacts", exact: true }).click();
  for (const kind of ["emergency contact", "guardian"]) {
    await page.getByRole("button", { name: `Add ${kind}`, exact: true }).click();
    await page.getByLabel("Contact name", { exact: false }).fill(kind === "guardian" ? "Browser Guardian" : "Browser Contact");
    await page.getByLabel("Relationship", { exact: false }).fill("Family");
    await page.getByLabel("Contact phone", { exact: false }).fill("01488887777");
    await page.getByRole("button", { name: "Save patient record" }).click();
    await expect(page.getByRole("dialog")).toBeHidden();
  }
  await expect(page.getByText("Browser Guardian", { exact: true })).toBeVisible();
  console.info("Patients: emergency contact and guardian saved");
  await page.getByRole("button", { name: "Addresses", exact: true }).click();
  await page.getByRole("button", { name: "Add address", exact: true }).click();
  await page.getByLabel("Address line 1", { exact: false }).fill("Browser Road");
  await page.getByLabel("City", { exact: true }).fill("Dhaka");
  await page.getByRole("button", { name: "Save patient record" }).click();
  await expect(page.getByRole("dialog")).toBeHidden();
  await expect(page.getByText(/Browser Road/)).toBeVisible();
  await page.getByRole("button", { name: "Identifiers", exact: true }).click();
  await page.getByRole("button", { name: "Add identifier", exact: true }).click();
  await page.getByLabel("Identifier type").selectOption("passport");
  await page.getByLabel("Identifier value", { exact: false }).fill("BROWSER-PASSPORT");
  await page.getByRole("button", { name: "Save patient record" }).click();
  await expect(page.getByRole("dialog")).toBeHidden();
  await page.getByRole("button", { name: "Timeline", exact: true }).click();
  await page.getByLabel("Timeline note", { exact: true }).fill("Identity and contact information reviewed.");
  await page.getByRole("button", { name: "Add note", exact: true }).click();
  await expect(page.getByText("Identity and contact information reviewed.", { exact: true })).toBeVisible();
  console.info("Patients: address, identifier and timeline saved");
  await page.goto("/patients/new"); await fillPatient();
  await page.getByRole("button", { name: "Register patient", exact: true }).click();
  await expect(page.getByText("Possible matches — review before proceeding")).toBeVisible();
  await page.getByLabel("I reviewed the matches; this is a different patient").check();
  await page.getByLabel("Reason for separate registration").fill("Separate registration reviewed for browser merge test.");
  await page.getByRole("button", { name: "Register patient", exact: true }).click();
  await expect(page).toHaveURL(/patients\/[0-9a-f-]+$/);
  const sourceId = page.url().split("/").at(-1), sourceMrn = await page.locator("p.font-mono").innerText();
  expect(sourceId).not.toBe(targetId);
  console.info("Patients: duplicate registration reviewed");
  await page.goto(`/patients/${targetId}`);
  await page.getByRole("button", { name: "Merge another profile" }).click();
  await page.getByLabel("Find source patient").fill(sourceMrn);
  await page.getByRole("button", { name: "Find patient", exact: true }).click();
  await page.getByRole("button", { name: `Compare ${sourceMrn}` }).click();
  await page.getByLabel("Reason for merge").fill("Confirmed duplicate patient profiles in browser review.");
  await page.getByLabel(`Type source MRN ${sourceMrn} to confirm`).fill(sourceMrn);
  await page.getByLabel("I reviewed both profiles and the selected values").check();
  await page.getByRole("button", { name: "Confirm patient merge" }).click();
  await expect(page.getByRole("dialog")).toBeHidden();
  await expect(page.getByRole("link", { name: sourceMrn, exact: true })).toBeVisible();
  console.info("Patients: merge completed");
  await page.goto(`/patients/${sourceId}`);
  await expect(page.getByText("This patient record has been merged and is read-only.")).toBeVisible();
  await page.getByRole("link", { name: /^Open Browser Patient/ }).click();
  await expect(page).toHaveURL(new RegExp(targetId));
  await expect(page.getByRole("heading", { name: "Browser Patient", exact: true })).toBeVisible();
  await expect(page).toHaveTitle(/Patient profile/);
  await expect(new AxeBuilder({ page }).analyze().then((result) => result.violations)).resolves.toEqual([]);
  await page.goto("/patients");
  await page.getByLabel("Search patients", { exact: false }).fill(sourceMrn);
  const patientLink = page.getByRole("link", { name: /Browser Patient/ });
  await expect(patientLink).toHaveCount(1); await expect(patientLink).toHaveAttribute("href", `/patients/${targetId}`);
  expect(clientErrors).toEqual([]);
});
