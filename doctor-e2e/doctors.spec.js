const { test, expect } = require("@playwright/test");
const AxeBuilder = require("@axe-core/playwright").default;
test("doctors and departments can be created, edited and safely deleted", async ({ page }) => {
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/api/v1/**", async (route) => {
    const request = route.request();
    if (request.method() === "OPTIONS") return route.fulfill({ status: 204, headers: { "access-control-allow-origin": "http://127.0.0.1:3111", "access-control-allow-credentials": "true", "access-control-allow-headers": "authorization,content-type", "access-control-allow-methods": "GET,POST,PATCH,DELETE,OPTIONS" } });
    const url = new URL(request.url()), path = url.pathname.replace(/^.*\/api\/v1/, "");
    const response = await route.fetch({ url: process.env.E2E_API_BASEURL + path + url.search, timeout: 90000 });
    await route.fulfill({ response, headers: { ...response.headers(), "access-control-allow-origin": "http://127.0.0.1:3111", "access-control-allow-credentials": "true" } });
  });
  await page.goto("/login");
  await page.getByLabel("User ID or email", { exact: true }).fill(process.env.E2E_LOGIN_ID);
  await page.getByLabel("Password", { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole("button", { name: "Sign in", exact: true }).click(); await expect(page).toHaveURL(/\/dashboard/);
  await page.getByRole("link", { name: "Doctors", exact: true }).click({timeout:60000});
  await expect(page.getByRole("heading", { name: "Doctors", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Departments", exact: true })).toHaveCount(0);
  for (const name of ["Cardiology", "Neurology"]) {
    await page.getByRole("button", { name: "Create department", exact: true }).click();
    const dialog = page.getByRole("dialog"); await dialog.getByLabel("Department name", { exact: true }).fill(name);
    await dialog.getByRole("button", { name: "Create department", exact: true }).click(); await expect(dialog).toHaveCount(0);
  }
  await page.getByRole("button", { name: "Create doctor", exact: true }).click(); let dialog = page.getByRole("dialog");
  await dialog.getByLabel("First name", { exact: true }).fill("Browser");
  await dialog.getByLabel("Last name", { exact: true }).fill("Doctor");
  await dialog.getByLabel("New visit fee", {exact:true}).fill("650.50");
  await dialog.getByLabel("Follow-up fee", {exact:true}).fill("350.25");
  await dialog.getByLabel("Qualification (optional)", { exact: true }).fill("MBBS\nFCPS (Medicine)");
  await dialog.getByLabel("Room for all visiting days", {exact:true}).fill("201");
  await dialog.getByRole("checkbox", {name:"Monday",exact:true}).check();
  await dialog.getByLabel("Monday start", {exact:true}).fill("10:00");
  await dialog.getByLabel("Monday end", {exact:true}).fill("13:00");
  await dialog.getByRole("checkbox", {name:"Wednesday",exact:true}).check();
  await dialog.getByLabel("Select department", { exact: true }).selectOption({ label: "Cardiology" });
  await dialog.getByRole("button", { name: "Create doctor", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("Doctor created. Save these credentials before closing.");
  await expect(dialog.getByText(/D\d{5}/)).toBeVisible(); await dialog.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByRole("row", { name: /Browser Doctor.*Cardiology/ })).toBeVisible();
  await page.getByRole("row", { name: /Browser Doctor/ }).getByRole("button", { name: "View doctor", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("region", { name: "Qualifications" })).toHaveText(/MBBS\s+FCPS \(Medicine\)/);
  await expect(page.getByRole("dialog").getByText("Monday", {exact:true})).toBeVisible();
  await expect(page.getByRole("dialog").getByText(/10:00 to 13:00/)).toBeVisible();
  await expect(page.getByRole("dialog").getByText("Room: 201", {exact:true})).toHaveCount(2);
  await expect(page.getByRole("dialog").getByText("650.50",{exact:true})).toBeVisible();
  await expect(page.getByRole("dialog").getByText("350.25",{exact:true})).toBeVisible();
  const detailsAccessibility = await new AxeBuilder({ page }).analyze(); expect(detailsAccessibility.violations).toEqual([]);
  await page.getByRole("button", { name: "Close details", exact: true }).click();
  console.log("Doctors: creation, qualifications and details passed");
  await page.getByRole("row", { name: /Existing Doctor/ }).getByRole("button", { name: "Edit doctor", exact: true }).click(); dialog = page.getByRole("dialog");
  await dialog.getByLabel("Select department", { exact: true }).selectOption({ label: "Cardiology" });
  await dialog.getByRole("button", { name: "Save changes", exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("row", { name: /Existing Doctor.*Cardiology/ })).toBeVisible();
  await page.getByRole("button", { name: "Departments", exact: true }).click();
  await page.getByRole("row", { name: /Cardiology/ }).getByRole("button", { name: "Edit department", exact: true }).click(); dialog = page.getByRole("dialog");
  await dialog.getByLabel("Department name", { exact: true }).fill("Heart Care");
  await dialog.getByRole("button", { name: "Save changes", exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("row", { name: /Heart Care 2/ })).toBeVisible();
  await page.getByRole("row", { name: /Heart Care/ }).getByRole("button", { name: "Delete department", exact: true }).click(); dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("button", { name: "Delete department", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: "Doctors", exact: true }).click();
  await page.getByRole("row", { name: /Browser Doctor/ }).getByRole("button", { name: "Edit doctor", exact: true }).click(); dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Monday start", {exact:true})).toHaveValue("10:00");
  await dialog.getByRole("button", {name:"Different rooms by day",exact:true}).click();
  await expect(dialog.getByLabel("Monday room",{exact:true})).toHaveValue("201");
  await dialog.getByLabel("Wednesday room",{exact:true}).fill("305");
  await dialog.getByLabel("Wednesday end", {exact:true}).fill("14:07");
  await expect(dialog.getByLabel("New visit fee",{exact:true})).toHaveValue("650.50");
  await dialog.getByLabel("New visit fee",{exact:true}).fill("700");
  await dialog.getByLabel("Follow-up fee",{exact:true}).fill("400");
  await dialog.getByLabel("Last name", { exact: true }).fill("Updated");
  await expect(dialog.getByLabel("Qualification (optional)", { exact: true })).toHaveValue("MBBS\nFCPS (Medicine)");
  await dialog.getByLabel("Qualification (optional)", { exact: true }).fill("MBBS\nMD (Neurology)");
  await dialog.getByLabel("Phone (optional)", { exact: true }).fill("01712345678");
  await dialog.getByLabel("Select department", { exact: true }).selectOption({ label: "Neurology" });
  await dialog.getByRole("button", { name: "Save changes", exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("row", { name: /Browser Updated.*Neurology.*01712345678/ })).toBeVisible();
  await page.getByRole("row", { name: /Browser Updated/ }).getByRole("button", { name: "View doctor", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("region", { name: "Qualifications" })).toHaveText(/MBBS\s+MD \(Neurology\)/);
  await expect(page.getByRole("dialog").getByText("Room: 201",{exact:true})).toBeVisible();
  await expect(page.getByRole("dialog").getByText("Room: 305",{exact:true})).toBeVisible();
  await expect(page.getByRole("dialog").getByText("700.00",{exact:true})).toBeVisible();
  await page.getByRole("button", { name: "Close details", exact: true }).click();
  const accessibility = await new AxeBuilder({ page }).analyze(); expect(accessibility.violations).toEqual([]);
  await page.getByRole("link", { name: "Appointments", exact: true }).click();
  const visitingDate=new Date();visitingDate.setUTCDate(visitingDate.getUTCDate()+((1-visitingDate.getUTCDay()+7)%7));
  const appointmentDate=page.getByLabel("Date (Bangladesh time)",{exact:true});
  await expect(appointmentDate).toHaveValue(new Intl.DateTimeFormat("en-CA",{timeZone:"Asia/Dhaka"}).format(new Date()));
  await appointmentDate.fill(visitingDate.toISOString().slice(0,10));
  await appointmentDate.press("Tab");
  await page.getByRole("button",{name:"Refresh",exact:true}).click();
  await expect(page.getByLabel("Doctor", { exact: true }).getByRole("option", { name: "Browser Updated", exact: true })).toHaveCount(1);
  await expect(page.getByText("No appointments found", { exact: true })).toBeVisible();
  await expect(page.getByRole("button",{name:"Add doctor schedule",exact:true})).toHaveCount(0);
  await page.getByRole("link", { name: "Doctors", exact: true }).click();
  await page.getByRole("row", { name: /Browser Updated/ }).getByRole("button", { name: "Delete doctor", exact: true }).click(); dialog = page.getByRole("dialog");
  await expect(dialog.getByText("Browser Updated", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Delete doctor", exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("row", { name: /Browser Updated/ })).toHaveCount(0);
  await page.getByRole("button", { name: "Departments", exact: true }).click();
  await page.getByRole("row", { name: /Neurology/ }).getByRole("button", { name: "Delete department", exact: true }).click(); dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Delete department", exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("row", { name: /Neurology/ })).toHaveCount(0);
  console.log("Doctors: editing, reassignment, guarded and successful deletion passed");
  await page.unrouteAll({ behavior: "wait" }); expect(errors).toEqual([]);
});
